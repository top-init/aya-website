#!/usr/bin/env node
// Vendors the onboarding flow (steps config + the copy it keys into) from the
// app repo, which owns it. The funnel must ask the SAME questions in the SAME
// words as the app — a paying user who lands in the app after the funnel would
// otherwise meet a second, different onboarding.
//
//   node scripts/sync-onboarding-flow.mjs           # write vendor/onboarding-flow
//   node scripts/sync-onboarding-flow.mjs --check   # fail if the copy has drifted
//
// Source repo: $AYA_APP_REPO, else the sibling ../aya-manifest-app checkout.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const APP_REPO = resolve(process.env.AYA_APP_REPO || join(WEB_ROOT, "..", "aya-manifest-app"));
const OUT = join(WEB_ROOT, "vendor", "onboarding-flow");
const CHECK = process.argv.includes("--check");

// Which locales the funnel serves. The app ships ~156; carrying all of them
// here would put 19MB of JSON in the Next bundle for languages we are not
// buying ads in. Add a locale here when a market opens — the copy already
// exists upstream, so it is a one-line change, not a translation job.
const FUNNEL_LOCALES = [
  "en",
  "en-GB",
  "en-AU",
  "en-CA",
  "es",
  "es-MX",
  "es-419",
  "pt-BR",
  "fr",
  "de",
  "it",
  "nl",
  "pl",
];

const SOURCE_FILES = [
  "packages/onboarding-flow/src/index.ts",
  "packages/onboarding-flow/src/steps.ts",
  "packages/onboarding-flow/src/name-pre.ts",
  "packages/onboarding-flow/src/persona.ts",
];

function fail(msg) {
  console.error(`sync-onboarding-flow: ${msg}`);
  process.exit(1);
}

function read(rel) {
  const abs = join(APP_REPO, rel);
  if (!existsSync(abs)) fail(`missing in app repo: ${rel}`);
  return readFileSync(abs);
}

function sourceRef() {
  try {
    return execFileSync("git", ["-C", APP_REPO, "rev-parse", "HEAD"], {
      encoding: "utf8",
    }).trim();
  } catch {
    return "unknown";
  }
}

if (!existsSync(APP_REPO)) {
  // Deploy builds (Vercel) only ever have this repo checked out, so there is
  // nothing to compare against — the vendored copy IS the input there. Drift is
  // caught where both repos exist: a developer machine and CI.
  if (CHECK) {
    console.log(`sync-onboarding-flow: app repo not present at ${APP_REPO} — skipping drift check`);
    process.exit(0);
  }
  fail(`app repo not found at ${APP_REPO} — set AYA_APP_REPO to its checkout`);
}

// Build the payload in memory first so --check never touches the working tree.
const files = new Map();

for (const rel of SOURCE_FILES) {
  files.set(`src/${rel.split("/").pop()}`, read(rel));
}

const available = new Set(
  readdirSync(join(APP_REPO, "locales")).filter((f) => f.endsWith(".json")),
);
for (const locale of FUNNEL_LOCALES) {
  const file = `${locale}.json`;
  if (!available.has(file)) fail(`locale ${locale} has no translations upstream`);
  files.set(`locales/${file}`, read(`locales/${file}`));
}

const digest = createHash("sha256");
for (const key of [...files.keys()].sort()) digest.update(key).update(files.get(key));
files.set(
  "SOURCE.json",
  Buffer.from(
    `${JSON.stringify(
      {
        repo: "aya-manifest-app",
        ref: sourceRef(),
        locales: FUNNEL_LOCALES,
        contentHash: digest.copy().digest("hex"),
        note: "Generated by scripts/sync-onboarding-flow.mjs. Do not edit by hand — edit the app repo.",
      },
      null,
      2,
    )}\n`,
  ),
);

if (CHECK) {
  const drifted = [];
  for (const [rel, buf] of files) {
    // SOURCE.json carries the upstream commit, which moves on every app commit
    // even when the flow itself did not. Drift is about content.
    if (rel === "SOURCE.json") continue;
    const abs = join(OUT, rel);
    if (!existsSync(abs) || !readFileSync(abs).equals(buf)) drifted.push(rel);
  }
  const stamp = join(OUT, "SOURCE.json");
  const recordedHash = existsSync(stamp) ? JSON.parse(readFileSync(stamp, "utf8")).contentHash : null;
  if (drifted.length || recordedHash !== digest.digest("hex")) {
    fail(
      `vendored onboarding flow is out of date (${drifted.length} file(s) differ).\n` +
        `Run: node scripts/sync-onboarding-flow.mjs`,
    );
  }
  console.log("sync-onboarding-flow: vendored copy matches the app repo");
  process.exit(0);
}

rmSync(OUT, { recursive: true, force: true });
for (const [rel, buf] of files) {
  const abs = join(OUT, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, buf);
}
console.log(
  `sync-onboarding-flow: wrote ${files.size} files to vendor/onboarding-flow (ref ${sourceRef().slice(0, 8)})`,
);
